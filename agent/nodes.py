
from langchain_ollama import ChatOllama


llm = ChatOllama(
    model="gemma2:2b",
    temperature=0
)



def make_retrieve_node(vector_store):

    def retrieve_node(state):

        print("\n--- RETRIEVING DOCUMENTS WITH MMR ---")

        retriever = vector_store.as_retriever(
            search_type="mmr",
            search_kwargs={
                "k": 5,
                "fetch_k": 20,
                "lambda_mult": 0.5
            }
        )

        documents = retriever.invoke(state["question"])

        # Remove duplicate chunks
        unique_documents = []
        seen_content = set()

        for doc in documents:
            content = doc.page_content.strip()

            if content not in seen_content:
                seen_content.add(content)
                unique_documents.append(doc)

        print("Retrieved chunks:", len(unique_documents))

        return {
            "documents": unique_documents
        }

    return retrieve_node


def grade_node(state):
    """Check whether retrieved documents are relevant."""

    print("\n--- GRADING DOCUMENTS ---")

    documents = state["documents"]

    if not documents:
        return {"relevant": False}

    context = "\n\n".join(
        doc.page_content for doc in documents
    )

    prompt = f"""
You are evaluating retrieved documentation.

Question:
{state["question"]}

Retrieved documentation:
{context}

Are these documents relevant to answering the question?

Respond with ONLY:
YES
or
NO
"""

    response = llm.invoke(prompt)
    result = response.content.strip().upper()

    relevant = result.startswith("YES")

    print("Documents relevant:", relevant)

    return {"relevant": relevant}


def rewrite_node(state):
    """Rewrite the question to improve retrieval."""

    print("\n--- REWRITING QUESTION ---")

    prompt = f"""
Rewrite the following question to make it clearer
and improve document retrieval.

Original question:
{state["original_question"]}

Current search question:
{state["question"]}

Return ONLY the improved search question.
Do not answer the question.
"""

    response = llm.invoke(prompt)

    new_question = response.content.strip()

    print("New search question:", new_question)

    return {
        "question": new_question,
        "retries": state["retries"] + 1
    }

def get_unique_sources(documents):
    sources = []

    for document in documents:
        source = document.metadata.get("source")

        if source and source not in sources:
            sources.append(source)

    return sources

def generate_node(state):
    """Generate an answer using retrieved documentation."""

    print("\n--- GENERATING ANSWER ---")

    context_parts = []

    for index, doc in enumerate(state["documents"], start=1):
        context_parts.append(
            f"[Source {index}]\n{doc.page_content}"
        )

    context = "\n\n".join(context_parts)

    prompt = f"""
You are DocuMind AI, a technical documentation assistant.

Answer the user's original question using ONLY the
provided documentation.

Rules:
- Do not invent information.
- If the documentation does not contain the answer,
  clearly say that.
- Explain technical concepts clearly.
- Include source references like [Source 1].

Documentation:
{context}

Original user question:
{state["original_question"]}

Answer:
"""

    response = llm.invoke(prompt)

    sources = list(dict.fromkeys(
        doc.metadata.get("source", "Unknown source")
        for doc in state["documents"]
    ))

    # Extract the text generated by Ollama
    generation = response.content

    return {
    "generation": generation,
    "sources": get_unique_sources(state["documents"])
}


def fallback_node(state):
    """Return a safe response when retrieval fails."""

    print("\n--- INSUFFICIENT DOCUMENTATION ---")

    return {
        "generation": (
            "I couldn't find sufficiently relevant information "
            "in the provided documentation to answer this question. "
            "Try rephrasing your question or providing more documentation."
        ),
        "sources": []
    }


