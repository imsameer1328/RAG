def self_check_node(state):
    """Check whether the generated answer is supported by documents."""

    print("\n--- CHECKING ANSWER SUPPORT ---")

    context = "\n\n".join(
        doc.page_content for doc in state["documents"]
    )

    prompt = f"""
You are a factual accuracy evaluator.

Documentation:
{context}

Generated answer:
{state["generation"]}

Determine whether the claims in the generated answer
are supported by the documentation.

Respond with ONLY:
YES
or
NO
"""

    response = llm.invoke(prompt)
    result = response.content.strip().upper()

    supported = result.startswith("YES")

    print("Answer supported:", supported)

    return {"answer_supported": supported}


def regenerate_node(state):
    """Regenerate an answer using only the retrieved evidence."""

    print("\n--- REGENERATING ANSWER ---")

    context = "\n\n".join(
        doc.page_content for doc in state["documents"]
    )

    prompt = f"""
You are DocuMind AI.

Answer the original question using ONLY the documentation below.

Original question:
{state["original_question"]}

Documentation:
{context}

Previous answer:
{state["generation"]}

Instructions:
- Remove unsupported claims.
- Do not invent information.
- Clearly explain when information is unavailable.
- Include source references such as [Source 1].

Generate the corrected answer:
"""

    response = llm.invoke(prompt)

    return {
        "generation": response.content,
        "answer_retries": state["answer_retries"] + 1
    }
